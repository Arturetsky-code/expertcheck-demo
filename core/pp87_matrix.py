def rules_for_section(section: str) -> list[dict[str, Any]]:
    sec=str(section or '').upper()
    if sec.startswith('ИОС'):
        return [
            {'id':'PP87-IOS-01','question':'Сведения об инженерном оборудовании, сетях и системах и принятых решениях','terms':['инженерн','сеть','систем','оборудован']},
            {'id':'PP87-IOS-02','question':'Расчетные расходы, мощности, нагрузки и параметры систем — по применимости','terms':['расход','мощност','нагрузк','давлен']},
            {'id':'PP87-IOS-03','question':'Описание источников, точек подключения, резервирования и учета — по применимости','terms':['источник','подключен','резерв','учет']},
        ]
    return PP87_BASELINE.get(sec, [])


def _evaluate_rule(rule: dict[str,Any], blob: str, *, prefix: str='ПП №87') -> dict[str,Any]:
    terms=[normalize_text(t) for t in rule.get('terms') or []]
    matched=[t for t in terms if t and t in blob]
    threshold=max(1,min(3,(len(terms)+1)//2))
    status='Да' if len(matched)>=threshold else ('Требует проверки' if matched else 'Нет')
    return {
        'item_no':rule['id'],
        'question':prefix+' · '+rule['question'],
        'status':status,
        'evidence':'Найдены признаки: '+', '.join(matched) if matched else 'Релевантные сведения автоматически не найдены.',
        'automation_level':'B','is_heading':False,'source_file':'Контрольная матрица ПП №87','compiled_rule':{
            'rule_type':'pp87_baseline','evidence_terms':rule.get('terms') or [],'requires_semantic_review':True,'source':PP87_SOURCE,
        },
    }


def evaluate_pp87(section: str, findings: list[dict[str, Any]]) -> list[dict[str, Any]]:
    blob=normalize_text(' '.join(' '.join(str(f.get(k) or '') for k in ('context','section_title','table_title','value_text','parameter_name','object_hint','match_method')) for f in findings))
    rows=[]
    for rule in rules_for_section(section):
        row=_evaluate_rule(rule,blob)
        row['document_types']=[section]
        rows.append(row)
    profile=detect_pp87_profile(findings)
    for rule in PROFILE_RULES.get(profile.get('profile'),[]):
        row=_evaluate_rule(rule,blob,prefix='ПП №87 · профиль объекта')
        row['document_types']=[section]
        row['profile']=profile.get('profile')
        rows.append(row)
    # Applicable PP87 appendices are surfaced as mandatory expert-control rows.
    for appendix in profile.get('appendices') or []:
        code=appendix.get('code')
        rows.append({
            'item_no':code,
            'question':'ПП №87 · '+APPENDIX_RULES.get(code, appendix.get('title','Специальное приложение ПП №87')),
            'status':'Требует проверки',
            'evidence':'Признаки применимости: '+', '.join(appendix.get('evidence') or []),
            'automation_level':'B','is_heading':False,'source_file':'Контрольная матрица ПП №87','document_types':[section],
            'profile':profile.get('profile'),'compiled_rule':{'rule_type':'pp87_appendix','requires_semantic_review':True,'appendix':code,'source':PP87_SOURCE},
        })
    return rows
