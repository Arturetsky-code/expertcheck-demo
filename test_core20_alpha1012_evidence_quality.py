from core20.evidence_quality_1012 import (
    is_toc_or_index_page,
    rank_candidates_quality,
    topic_alignment,
)


def test_toc_continuation_without_heading_is_rejected():
    page = (
        "RAM-0207.4-ЗД-ПД-АР1 Раздел 3. Объёмно-планировочные и архитектурные решения "
        "Часть 1. Текстовая часть Л и с т |5 "
        "2.3 Описание и обоснование принятых архитектурных решений, направленных на повышение "
        "энергетической эффективности объекта капитального строительства ........................ 22 "
        "3 Описание и обоснование использованных композиционных приемов при оформлении фасадов "
        "и интерьеров объекта капитального строительства ........................................ 39 "
        "4 Описание и обоснование решений по отделке помещений ................................... 44 "
        "5.1 Результаты расчетов продолжительности инсоляции и коэффициента естественной "
        "освещенности ............................................................................. 51"
    )
    assert "содержание" not in page.casefold()
    assert is_toc_or_index_page(page) is True


def test_topic_alignment_ignores_repeated_pzu_header():
    contract = {
        "topic": "Планировочная организация",
        "keywords": ["планировочная организация", "размещение объектов"],
    }
    transport_page = (
        "RAM-0207.4-ЗД-ПД-ПЗУ1 Площадка ДСК Раздел 2. Схема планировочной организации "
        "земельного участка Часть 1. Текстовая часть Л и с т |28 "
        "9 Обоснование схем транспортных коммуникаций, обеспечивающих внешний и внутренний "
        "подъезд к объектам. Проектом предусмотрены автомобильные проезды и площадки."
    )
    planning_page = (
        "RAM-0207.4-ЗД-ПД-ПЗУ1 Площадка ДСК Раздел 2. Схема планировочной организации "
        "земельного участка Часть 1. Текстовая часть Л и с т |10 "
        "2 Обоснование и описание решений по планировочной организации. Проектируемые здания "
        "размещены с учетом технологических связей и требований генерального плана."
    )
    wrong = topic_alignment(contract, transport_page)
    right = topic_alignment(contract, planning_page)
    assert wrong["eligible"] is False
    assert right["eligible"] is True


def test_quality_ranking_drops_header_only_false_positive():
    contract = {
        "topic": "Планировочная организация",
        "keywords": ["планировочная", "организация", "транспорт"],
    }
    transport = {
        "document": "ПЗУ1.pdf",
        "page": 29,
        "document_type": "ПЗУ",
        "text": (
            "RAM ПЗУ Схема планировочной организации земельного участка Л и с т |28 "
            "9 Обоснование схем транспортных коммуникаций. Автомобильные дороги и проезды."
        ),
    }
    planning = {
        "document": "ПЗУ1.pdf",
        "page": 11,
        "document_type": "ПЗУ",
        "text": (
            "RAM ПЗУ Схема планировочной организации земельного участка Л и с т |10 "
            "2 Планировочная организация территории. Размещение проектируемых объектов и площадок."
        ),
    }
    ranked = rank_candidates_quality(contract, [transport, planning])
    assert [item[3]["page"] for item in ranked] == [11]


def test_presence_candidate_on_toc_never_reaches_ranked_evidence():
    contract = {
        "topic": "Защита от шума и вибрации",
        "keywords": ["шум", "вибрац"],
    }
    toc_page = {
        "document": "АР1.pdf",
        "page": 5,
        "document_type": "АР",
        "text": (
            "RAM АР1 Л и с т |5 Защита от шума и вибрации ......................................... 49 "
            "Результаты расчетов инсоляции ......................................................... 51 "
            "Описание отделки помещений ........................................................... 44"
        ),
    }
    assert rank_candidates_quality(contract, [toc_page]) == []
